#include <stdio.h>

int main() {
    // Declare and assign a value
    int steps = 6000;
    // Declare a variable
    int duration;

    // Assign a value
    duration = 60 * 60; // 1 hour

    printf("Steps: %d\n", steps);
    printf("Duration: %d\n", duration);

    return 0;
}
